// Dependency names are compared case-insensitively; a trailing * in the pattern means "starts with".
export function depMatches(pattern, depName) {
  const a = depName.toLowerCase();
  const p = pattern.toLowerCase();
  return p.endsWith("*") ? a.startsWith(p.slice(0, -1)) : a === p;
}
